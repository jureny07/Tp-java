    private void AcheterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AcheterActionPerformed
        // TODO add your handling code here:
    String nom = nom_util.getText().trim();
    String tel = tel_util.getText().trim();
    facture_area.setText("");

    if (nom.isEmpty() || tel.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Veuillez entrer le nom et le numéro de téléphone",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    
    if (!tel.matches("\\d+")) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Le numéro de téléphone doit contenir uniquement des chiffres",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    
    if (tel.length() == 11) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Le numéro de téléphone ne doit pas dépasser 10 chiffres",
                "Erreur", javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }
       facture_area.append("========= FACTURE =========\n");
    facture_area.append("Client : " + nom + "\n");
    facture_area.append("Téléphone : " + tel + "\n");
    facture_area.append("--------------------------------\n");
    facture_area.append(String.format("%-15s %5s %10s %10s\n", "Article", "Qté", "PU", "Total"));
    facture_area.append("--------------------------------\n");
    
    double totalHT = 0 ;

    if (riz.isSelected()) {
        int qte = (int) riz_qte.getValue();
        double prix = 2000;
        ajouterArticle("Riz", qte, prix);
        totalHT += qte*prix;
    }

    if (sucre.isSelected()) {
        int qte = (int) sucre_qte.getValue();
        double prix = 3800;
        ajouterArticle("Sucre", qte, prix);
        totalHT += qte*prix;
    }

    if (farine.isSelected()) {
        int qte = (int) farine_qte.getValue();
        double prix = 3000;
        ajouterArticle("Farine", qte, prix);
        totalHT += qte*prix;
    }

    if (haricot.isSelected()) {
        int qte = (int) haricot_qte.getValue();
        double prix = 2500;
        ajouterArticle("Haricot", qte, prix);
        totalHT += qte*prix;
    }

    if (semoule.isSelected()) {
        int qte = (int) semoule_qte.getValue();
        double prix = 2500;
        ajouterArticle("Semoule", qte, prix);
        totalHT += qte*prix;
    }

    if (huile.isSelected()) {
        int qte = (int) huile_qte.getValue();
        double prix = 1500;
        ajouterArticle("Huile", qte, prix);
        totalHT += qte*prix;
    }

    if (pain.isSelected()) {
        int qte = (int) pain_qte.getValue();
        double prix = 1500;
        ajouterArticle("Pain", qte, prix);
        totalHT += qte*prix;
    }

    if (savon.isSelected()) {
        int qte = (int) savon_qte.getValue();
        double prix = 2000;
        ajouterArticle("Savon", qte, prix);
        totalHT += qte*prix;
    }

    if (sel.isSelected()) {
        int qte = (int) sel_qte.getValue();
        double prix = 1500;
        ajouterArticle("Sel", qte, prix);
        totalHT += qte*prix;
    }

    if (lotion.isSelected()) {
        int qte = (int) lotion_qte.getValue();
        double prix = 4500;
        ajouterArticle("Lotion", qte, prix);
        totalHT += qte*prix;
    }

    if (tomate.isSelected()) {
        int qte = (int) tomate_qte.getValue();
        double prix = 200;
        ajouterArticle("Tomate", qte, prix);
        totalHT += qte*prix;
    }

    if (arachide.isSelected()) {
        int qte = (int) arachide_qte.getValue();
        double prix = 1500;
        ajouterArticle("Arachide", qte, prix);
        totalHT += qte*prix;
    }

    if (vin.isSelected()) {
        int qte = (int) vin_qte.getValue();
        double prix = 45000;
        ajouterArticle("Vin", qte, prix);
        totalHT += qte*prix;
    }

    if (biere.isSelected()) {
        int qte = (int) biere_qte.getValue();
        double prix = 2500;
        ajouterArticle("Biere", qte, prix);
        totalHT += qte*prix;
    }

    if (allumette.isSelected()) {
        int qte = (int) allumette_qte.getValue();
        double prix = 300;
        ajouterArticle("Allumette", qte, prix);
        totalHT += qte*prix;
    }

    if (cure_dent.isSelected()) {
        int qte = (int) cure_dent_qte.getValue();
        double prix = 300;
        ajouterArticle("Cure dent", qte, prix);
        totalHT += qte*prix;
    }

    if (piment.isSelected()) {
        int qte = (int) piment_qte.getValue();
        double prix = 50;
        ajouterArticle("Piment", qte, prix);
        totalHT += qte*prix;
    }

    if (whisky.isSelected()) {
        int qte = (int) whisky_qte.getValue();
        double prix = 20000;
        ajouterArticle("Whisky", qte, prix);
        totalHT += qte*prix;
    }

    if (poulet.isSelected()) {
        int qte = (int) poulet_qte.getValue();
        double prix = 2500;
        ajouterArticle("Poulet", qte, prix);
        totalHT += qte*prix;
    }

    if (sardine.isSelected()) {
        int qte = (int) sardine_qte.getValue();
        double prix = 2000;
        ajouterArticle("Sardine", qte, prix);
        totalHT += qte*prix;
    }

    if (corned_beef.isSelected()) {
        int qte = (int) corned_beef_qte.getValue();
        double prix = 4500;
        ajouterArticle("Corned beef", qte, prix);
        totalHT += qte*prix;
    }
        
         
    double TVA = totalHT * 0.16;
    double totalTTC = totalHT + TVA;
    double remise = 0;

    if (totalHT >= 220000) {
        remise = totalTTC * 0.30; 
        totalTTC -= remise;
    }

    
    facture_area.append("--------------------------------\n");
    facture_area.append(String.format("Total HT     : %36.2f FC\n", totalHT));
    facture_area.append(String.format("TVA (16%%)    : %36.2f FC\n", TVA));
    if (remise > 0) {
        facture_area.append(String.format("Remise 30%%   : -%34.2f FC\n", remise));
    }
    facture_area.append(String.format("TOTAL TTC    : %36.2f FC\n", totalTTC));
    facture_area.append("==============================\n");

    javax.swing.JOptionPane.showMessageDialog(this,
            "Client : " + nom + "\nTéléphone : " + tel + 
            "\nTOTAL À PAYER : " + totalTTC + " FC",
            "FACTURE", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    
    }//GEN-LAST:event_AcheterActionPerformed

