    private void ajouterArticle(String nom, int qte, double prix) {
    if (qte > 0) {
        double sousTotal = qte * prix;
        facture_area.append(
            String.format("%-15s %5d x %8.2f = %8.2f FC\n",
                    nom, qte, prix, sousTotal)
        );
    }
    }
   

